"""
config.py - 戦略パラメータの一元管理

このファイルを変更するだけで戦略全体が変わる設計にしている。
コード各所にパラメータを散らばらせると、変更時に漏れが生じるため
すべての設定値をここに集約する（単一責任の原則）。
"""

# ============================================================
# 移動平均線の設定
# ============================================================
# 20日移動平均線を使用する理由:
# - 約1ヶ月の平均コストを表す短期トレンドの基準線
# - Woodstockアプリで確認できる（運用との一致）
# - スイングトレード（数日〜2週間）に適した期間
MA_PERIOD: int = 20

# 移動平均線の「上向き」を確認する日数
# 5日前より今日の移動平均線が高ければ上昇トレンドと判定
MA_SLOPE_DAYS: int = 5

# ============================================================
# 乖離率の設定
# ============================================================
# 乖離率 = (現在値 - 移動平均線) / 移動平均線
#
# 下限(+2%)の理由:
# - 移動平均線を明確に上抜けたことを確認するため
# - +2%未満はまだトレンドが弱い可能性がある
#
# 上限(+10%)の理由:
# - 上がりすぎた銘柄は「平均回帰」で下落しやすい
# - 飛びついた高値掴みを防ぐため
DEVIATION_MIN: float = 0.03   # 乖離率の下限
DEVIATION_MAX: float = 0.08   # 乖離率の上限

# ============================================================
# ボラティリティフィルター（ATRベース）
# ============================================================
# ATR（Average True Range）= 過去N日間の平均的な値動き幅
# 株価に対するATRの割合でボラティリティを測定する
#
# なぜボラフィルターを入れるか：
# - ボラが低すぎる銘柄は+6%の利確に届きにくい
# - 値動きが大きい銘柄の方がRR比2.0を活かしやすい
# - force_exit_loss（5日含み損）が減る可能性がある
#
# ATR_MIN_PCT = 0.015 の意味：
# 株価$100の銘柄なら1日平均$1.5以上動く銘柄だけを対象にする
ATR_PERIOD: int = 14          # ATRの計算期間（一般的な14日）
ATR_MIN_PCT: float = 0.015    # ATRが株価の1.5%以上の銘柄のみ

# ============================================================
# エグジット条件
# ============================================================
# RR比（リスクリワード比）= 利確幅 / 損切り幅 = 6% / 3% = 2.0
# RR比2.0の意味: 勝率34%以上でトータルプラスになる
# 例: 10回中4回勝ち(+6%) 6回負け(-3%) → 期待値 = 0.4×6 - 0.6×3 = +0.6%
TAKE_PROFIT: float = 0.06     # 利確ライン（+6%）
STOP_LOSS: float = 0.03       # 損切りライン（-3%）

# Woodstockの逆指値注文で損切りを自動化する
# → 購入直後に購入単価の-3%に逆指値注文を入れる運用

# ============================================================
# 保有期間の設定
# ============================================================
# 塩漬けを防ぐための強制決済ルール
#
# 5営業日後に含み損 → 強制決済通知（負けを早く切る）
# 10営業日後      → 無条件で強制決済通知
# 理由: スイングトレードの想定期間（1〜2週間）を超えた保有は
#       当初の戦略から外れているため
FORCE_EXIT_LOSS_DAYS: int = 7    # 含み損の場合の強制決済日数
FORCE_EXIT_MAX_DAYS: int = 15    # 無条件強制決済日数

# ============================================================
# 市場環境フィルター
# ============================================================
# VIX（恐怖指数）の閾値
# VIXは市場参加者の「恐怖度」を数値化したもの（人間の心理指標）
# VIX < 25: 市場が比較的落ち着いている状態
# VIX > 25: 市場が不安定で個別株も巻き込まれやすい状態
# 通常相場のVIXは12〜20程度で推移するため、
# このフィルターが機能するのは年に数回程度
VIX_THRESHOLD: float = 23.0

# SPY（S&P500 ETF）の長期トレンドフィルター
# 市場全体のモメンタムが上向きの時だけ買う
# 200日移動平均線 = 約10ヶ月の平均コスト（長期トレンドの基準）
# SPY > 200日線: 市場全体が長期上昇トレンド中
# SPY < 200日線: 市場全体が下落トレンド（個別株も影響を受けやすい）
SPY_MA_PERIOD: int = 200
# SPYの短期・中期モメンタム確認期間
# 20日線・50日線が上向きであることを確認する
# → 市場全体の短期・中期トレンドが上向きの時だけ買う
SPY_MA_SHORT: int = 20   # 短期移動平均（約1ヶ月）
SPY_MA_MID: int = 50     # 中期移動平均（約2.5ヶ月）
SPY_SLOPE_DAYS: int = 5  # 上向き確認の日数（銘柄と同じ基準）
# ============================================================
# ポジション管理
# ============================================================
# 同時保有の最大銘柄数
# 5〜10銘柄に分散することでリスクを分散する
MAX_POSITIONS: int = 10

# ケリー基準の安全係数
# ケリー基準の計算値をそのまま使うと破産リスクが高いため
# 一般的に0.5（ハーフケリー）を掛けて保守的に運用する
KELLY_FRACTION: float = 0.5

# ============================================================
# スクリーニング対象
# ============================================================
# S&P500構成銘柄を対象とする
# データソース: github.com/datasets/s-and-p-500-companies
# ライセンス: Open Data Commons PDDL
SP500_URL: str = (
    "https://raw.githubusercontent.com/datasets/"
    "s-and-p-500-companies/main/data/constituents.csv"
)

# ============================================================
# 通知設定
# ============================================================
# 損切りチェックの実行時刻（毎日）
ALERT_TIMES: list = ["09:00", "22:00"]

# 週次スクリーニングの実行曜日・時刻
SCREENING_DAY: str = "saturday"
SCREENING_TIME: str = "08:00"

# ============================================================
# データ取得設定
# ============================================================
# yfinanceでのデータ取得期間
# バックテスト: 過去5年分
# リアルタイム監視: 過去1年分（移動平均計算に必要な最小期間）
BACKTEST_PERIOD: str = "5y"
MONITOR_PERIOD: str = "1y"